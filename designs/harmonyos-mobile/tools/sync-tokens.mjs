#!/usr/bin/env node
// sync-tokens.mjs — regenerate this design system's token files from the
// HarmonyOS reference library, so the values are derived rather than hand-copied.
//
// Source of truth (read-only, never modified):
//   <ref>/references/2.theme/harmony-tokens.css   → colors.css + typography.css
//   <ref>/references/2.theme/mobile-scale.css     → spacing.css
//
// Tokens keep the reference's own `--harmony-*` names verbatim: consumers must be
// able to look a value up in the published spec, so renaming would break fidelity.
// The reference's multi-selector scopes are rewritten to `:root` (light) and a
// single-selector `[data-theme="dark"]`, which is what the compiler recognises.
//
// Usage:
//   node tools/sync-tokens.mjs [--ref <dir>] [--check]
//     --ref    reference library root (default: the local hmos skill)
//     --check  report drift vs. disk without writing (exit 1 if stale)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { annotateBody } from './lib/token-kind.mjs';

const DS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_REF = path.join(
  process.env.HOME || '', '.agents/skills/hmos-design-visual-mobile');

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
};
const REF = path.resolve(flag('--ref', DEFAULT_REF));
const CHECK = argv.includes('--check');

const TOKENS_CSS = path.join(REF, 'references/2.theme/harmony-tokens.css');
const SCALE_CSS = path.join(REF, 'references/2.theme/mobile-scale.css');

for (const f of [TOKENS_CSS, SCALE_CSS]) {
  if (!fs.existsSync(f)) {
    console.error(`sync-tokens: reference not found: ${f}`);
    console.error('  Pass --ref <dir> to point at the HarmonyOS reference library.');
    process.exit(2);
  }
}

/** Split flat CSS into [{ selector, body }] — the reference has no nested rules. */
function blocks(css) {
  const out = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    out.push({ selector: m[1].replace(/\/\*[\s\S]*?\*\//g, '').trim(), body: m[2].trim() });
  }
  return out;
}

const declared = (body) => (body.match(/--[a-zA-Z0-9_-]+\s*:/g) || []).length;

/* ---------------------------------------------------------------------------
 * Token kind annotation.
 *
 * The compiler only reads a kind from a comment placed IMMEDIATELY after the
 * declaration's semicolon (`--x: v; /* @kind color *\/`), so the reference's
 * own trailing `/* #aarrggbb *\/` note has to move behind it. Anything the
 * value alone cannot decide is settled by name, and whatever still does not
 * resolve is marked `other` on purpose rather than left unclassified.
 * ------------------------------------------------------------------------- */

/* Kind classification lives in tools/lib/token-kind.mjs, shared with the
   template importer so the two generators cannot disagree. The body is annotated
   as a whole, which also handles multi-line values. */
/** Rewrite a token block so every declaration carries `/* @kind x *\/` right
 *  after its semicolon, preserving any original trailing note behind it. */
function annotateLegacy(body) {
  const lines = body.split('\n');
  const decls = new Map();
  for (const raw of lines) {
    const m = /^\s*(--[A-Za-z0-9_-]+)\s*:\s*([^;]+);/.exec(raw);
    if (m) { decls.set(m[1], m[2].trim()); }
  }
  return lines.map((raw) => {
    const m = /^(\s*)(--[A-Za-z0-9_-]+)\s*:\s*([^;]+);\s*(.*)$/.exec(raw);
    if (!m) { return raw.trim(); }
    const [, indent, name, value, trailing] = m;
    const kind = kindOf(name, value, decls);
    const note = trailing && !/@kind/.test(trailing) ? ' ' + trailing : '';
    return `${indent}${name}: ${value.trim()}; /* @kind ${kind} */${note}`;
  }).join('\n');
}

function pick(list, test, label) {
  const hit = list.filter(test);
  if (hit.length !== 1) {
    console.error(`sync-tokens: expected exactly 1 ${label} block, found ${hit.length}`);
    process.exit(3);
  }
  return hit[0].body;
}

const tokenBlocks = blocks(fs.readFileSync(TOKENS_CSS, 'utf8'));
const isWearable = (b) => /wearable/.test(b.selector);

const typography = pick(
  tokenBlocks.filter((b) => !isWearable(b)),
  (b) => /--harmony-font-size-/.test(b.body),
  'typography');

const light = pick(
  tokenBlocks.filter((b) => !isWearable(b)),
  (b) => /data-theme="light"/.test(b.selector) && /--harmony-brand/.test(b.body),
  'light colour');

const dark = pick(
  tokenBlocks.filter((b) => !isWearable(b)),
  (b) => /data-theme="dark"/.test(b.selector) && /--harmony-brand/.test(b.body),
  'dark colour');

const scale = pick(
  blocks(fs.readFileSync(SCALE_CSS, 'utf8')),
  () => true,
  'page scale');

const banner = (what) => `/*
 * ${what}
 * GENERATED by tools/sync-tokens.mjs — do not edit by hand.
 * Source: HarmonyOS reference library —
 *   references/2.theme/harmony-tokens.css
 *   references/2.theme/mobile-scale.css
 * Re-run: node tools/sync-tokens.mjs [--ref <reference-library-root>]
 */`;

const files = {
  'tokens/typography.css': `${banner('HarmonyOS typography scale — theme-invariant')}

:root {
${annotateBody(typography).split('\n').map((l) => '  ' + l.trim()).join('\n')}
}
`,
  'tokens/colors.css': `${banner('HarmonyOS colour tokens — system set, light + dark')}

:root {
${annotateBody(light).split('\n').map((l) => '  ' + l.trim()).join('\n')}
}

[data-theme="dark"] {
${annotateBody(dark).split('\n').map((l) => '  ' + l.trim()).join('\n')}
}
`,
  'tokens/spacing.css': `${banner('HarmonyOS page scale — padding, radius, control heights, page geometry')}

:root {
${annotateBody(scale).split('\n').map((l) => '  ' + l.trim()).join('\n')}
}
`,
};

// The token tables are indented line by line, which turns an empty source line
// into a line holding nothing but spaces. The repo's commit hooks reject
// trailing whitespace, so normalise every generated file once, up front: --check
// compares exactly the strings that a write would produce.
for (const [rel, content] of Object.entries(files)) {
  files[rel] = content.replace(/[ \t]+$/gm, '');
}

let stale = 0;
for (const [rel, content] of Object.entries(files)) {
  const abs = path.join(DS, rel);
  const before = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (before === content) {
    console.log(`  = ${rel}`);
    continue;
  }
  stale += 1;
  if (CHECK) {
    console.log(`  ! ${rel} is stale`);
  } else {
    fs.writeFileSync(abs, content);
    console.log(`  ${before === null ? '+' : '~'} ${rel}`);
  }
}

console.log(`sync-tokens: ${Object.keys(files).length} files, ` +
  `${stale} ${CHECK ? 'stale' : 'updated'}  (source: ${REF})`);
console.log(`  tokens: typography ${declared(typography)}, ` +
  `light ${declared(light)}, dark ${declared(dark)}, scale ${declared(scale)}`);

if (CHECK && stale) { process.exit(1); }
