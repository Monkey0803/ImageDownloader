#!/usr/bin/env node
// import-template-css.mjs — translate the HarmonyOS reference component templates
// into this design system's group CSS.
//
// Why generate instead of hand-copy: the templates ARE the spec's numeric truth
// ("copy exact numeric values — never round"). Transcribing ~3000 lines of CSS by
// hand invites drift; this keeps every padding, radius and font-size byte-identical
// to references/4.template/*-tem.html.
//
// What it does, and deliberately does NOT do:
//   · extracts each template's <style> block
//   · strips @import (this system's tokens are already in the closure) and
//     @font-face (fonts.css owns them)
//   · renames .harmony-<name> → .hm-<name> so cards and components share one prefix
//   · leaves every declaration value untouched
//
// Usage:
//   node tools/import-template-css.mjs [--ref <dir>] [--check]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { annotateBody } from './lib/token-kind.mjs';

const DS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const flag = (n, d) => { const i = argv.indexOf(n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
const REF = path.resolve(flag('--ref', path.join(process.env.HOME || '', '.agents/skills/hmos-design-visual-mobile')));
const CHECK = argv.includes('--check');

const TPL = path.join(REF, 'references/4.template');
if (!fs.existsSync(TPL)) {
  console.error(`import-template-css: templates not found: ${TPL}`);
  process.exit(2);
}

/* Which templates feed which group. Order inside a group is the reference's own
   shell order: statusbar → titlebar → bottomtab → toolbar → aibottombar. */
const GROUPS = {
  shell: ['size', 'statusbar', 'titlebar', 'bottomtab', 'aibottombar', 'toolbar'],
  controls: ['button', 'switch', 'search', 'chipstab'],
  containers: ['cardview', 'list', 'divider'],
};

const HDR = (group, names) => `/*
 * ${group} components — TRANSLATED from the HarmonyOS reference templates.
 * GENERATED by tools/import-template-css.mjs — do not edit by hand; fix the
 * reference or the translator instead.
 *
 * Sources (references/4.template/):
${names.map((n) => ` *   ${n}-tem.html`).join('\n')}
 *
 * Values are copied verbatim — nothing is rounded or snapped to a grid.
 * @import and @font-face are stripped (owned by styles.css / fonts.css), and
 * .harmony-* is renamed to .hm-* so components and cards share one prefix.
 */`;

function extractStyle(file) {
  const html = fs.readFileSync(file, 'utf8');
  const styles = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => m[1]);
  if (!styles.length) {
    console.error(`import-template-css: no <style> block in ${path.basename(file)}`);
    process.exit(3);
  }
  return styles.join('\n');
}

/* The templates reference assets relative to the REFERENCE tree
   (`../../../assets/statusbar-wifi-light.png`). Once the CSS lives in
   components/<group>/, those paths resolve to nothing. Rewrite every url() whose
   basename we ship in assets/ to the correct relative path, and fail loudly on
   anything we do not ship — a silent 404 is worse than a build error. */
function rewriteAssetUrls(css, cssDirAbs) {
  return css.replace(/url\(\s*["']?([^"')]+)["']?\s*\)/g, (full, href) => {
    if (/^(data:|https?:|\/\/)/.test(href)) { return full; }
    const base = path.basename(href);
    const shipped = path.join(DS, 'assets', base);
    if (!fs.existsSync(shipped)) {
      console.error(`import-template-css: template references an asset we do not ship: ${href}`);
      console.error(`  expected it at assets/${base} — copy it there or drop the reference.`);
      process.exit(5);
    }
    let rel = path.relative(cssDirAbs, shipped).split(path.sep).join('/');
    if (!rel.startsWith('.')) { rel = './' + rel; }
    return `url("${rel}")`;
  });
}

function translate(css) {
  return css
    // the templates @import the reference tokens / declare the fonts; both are
    // already handled by this system's closure
    .replace(/^\s*@import[^;]+;/gm, '')
    .replace(/@font-face\s*\{[^}]*\}/g, '')
    .replace(/\.harmony-/g, '.hm-')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/* Stamp @kind on the template's own local variables too — the compiler indexes
   them (a component root selector counts as a single-selector scope), so an
   unannotated local shows up as an unclassified token in the checker. */
/* The reference authors parked component-local token dumps at `:root`. In a single
   template that is harmless; in a system it is a silent override, because the
   component CSS is imported LAST and a `:root` declaration from a component beats
   the token layer at equal specificity. Observed for real: containers.css
   re-declared --harmony-brand (light) and --harmony-divider-color, which killed the
   dark-mode flip for anything that set data-theme on <html> rather than on a frame.
   A component may not redefine a system token, so those declarations are dropped
   here — names the system does NOT define are left alone. */
function systemTokenNames() {
  const names = new Set();
  const dir = path.join(DS, 'tokens');
  if (!fs.existsSync(dir)) { return names; }
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.css')) { continue; }
    const src = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
    for (const m of src.matchAll(/(--[A-Za-z0-9_-]+)\s*:/g)) { names.add(m[1]); }
  }
  return names;
}

function dropTokenRedefinitions(css, systemTokens, group) {
  const dropped = [];
  const out = css.replace(/(:root\s*\{)([\s\S]*?)(\n\})/g, (full, open, body, close) => {
    const kept = body.split('\n').filter((line) => {
      const m = /^\s*(--[A-Za-z0-9_-]+)\s*:/.exec(line);
      if (m && systemTokens.has(m[1])) { dropped.push(m[1]); return false; }
      return true;
    });
    return open + kept.join('\n') + close;
  });
  if (dropped.length) {
    console.log(`  ! ${group}: dropped ${dropped.length} component-level redefinition(s) of system tokens: ${[...new Set(dropped)].join(', ')}`);
  }
  return out;
}

function translateAndAnnotate(css, cssDirAbs) {
  return annotateBody(dropTokenRedefinitions(rewriteAssetUrls(translate(css), cssDirAbs), systemTokenNames(), path.basename(path.dirname(cssDirAbs))));
}

let stale = 0;
for (const [group, names] of Object.entries(GROUPS)) {
  const cssDirAbs = path.join(DS, 'components', group);
  const parts = names.map((n) => {
    const file = path.join(TPL, `${n}-tem.html`);
    if (!fs.existsSync(file)) {
      console.error(`import-template-css: missing template ${n}-tem.html`);
      process.exit(4);
    }
    return `/* ---------- ${n} ---------- */\n\n${translateAndAnnotate(extractStyle(file), cssDirAbs)}`;
  });
  // The reference templates keep indentation-only lines; the repo's commit hooks
  // reject trailing whitespace, so strip it here — --check compares the same
  // normalised string this writes.
  const content = `${HDR(group, names)}\n\n${parts.join('\n\n')}\n`.replace(/[ \t]+$/gm, '');
  const abs = path.join(DS, `components/${group}/${group}.css`);
  const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (cur === content) { console.log('  = ' + path.relative(DS, abs)); continue; }
  stale++;
  if (CHECK) { console.log('  ! stale: ' + path.relative(DS, abs)); continue; }
  fs.writeFileSync(abs, content);
  console.log(`  ${cur === null ? '+' : '~'} ${path.relative(DS, abs)}  (${names.join(', ')})`);
}
console.log(`import-template-css: ${Object.keys(GROUPS).length} group files, ` +
  `${stale} ${CHECK ? 'stale' : 'written'}`);
if (CHECK && stale) { process.exit(1); }
